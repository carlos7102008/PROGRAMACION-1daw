public class Operadores_incremento {
    public  static void main(String args[]){
    int a = 1;    
    System.out.println("resultado de a " + a);
    
    int b = a ++;    
    System.out.println("resultado de a " + a);
    System.out.println("resultado de b " + b);
    int c = ++ a;
    
    System.out.println("resultado de a " + a);
    System.out.println("resultado de b " + b);
    System.out.println("resultado de c " + c);    
}
}


